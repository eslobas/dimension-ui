// Turns tokens/tokens.json into CSS custom properties and a typed TS object.
// Kept dependency-free on purpose: the format is a small subset of the W3C DTCG spec.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'tokens/tokens.json'), 'utf8'));

/** Flatten nested groups into [['color','blue','500'], '#4f8cff'] pairs. */
function flatten(node, path = [], out = []) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (value && typeof value === 'object' && '$value' in value) out.push([[...path, key], value.$value]);
    else if (value && typeof value === 'object') flatten(value, [...path, key], out);
  }
  return out;
}

const flat = flatten(tokens);
const byPath = new Map(flat.map(([p, v]) => [p.join('.'), v]));

/** Resolve "{color.blue.500}" references, failing loudly on typos or cycles. */
function resolveValue(value, seen = new Set()) {
  const match = /^\{(.+)\}$/.exec(value);
  if (!match) return value;
  const ref = match[1];
  if (seen.has(ref)) throw new Error(`Circular token reference: ${[...seen, ref].join(' -> ')}`);
  if (!byPath.has(ref)) throw new Error(`Unknown token reference {${ref}}`);
  return resolveValue(byPath.get(ref), new Set([...seen, ref]));
}

const cssName = (path) => `--dui-${path.join('-')}`;
const primitives = flat.filter(([p]) => p[0] !== 'theme');
const themes = Object.keys(tokens.theme);

const themeBlock = (name) =>
  flat
    .filter(([p]) => p[0] === 'theme' && p[1] === name)
    .map(([p, v]) => {
      const ref = /^\{(.+)\}$/.exec(v);
      const css = ref ? `var(${cssName(ref[1].split('.'))})` : v;
      return `  --dui-color-${p.slice(2).join('-')}: ${css};`;
    })
    .join('\n');

const css = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */
:root {
${primitives.map(([p, v]) => `  ${cssName(p)}: ${resolveValue(v)};`).join('\n')}
}

:root,
[data-theme='dark'] {
  color-scheme: dark;
${themeBlock('dark')}
}

[data-theme='light'] {
  color-scheme: light;
${themeBlock('light')}
}
`;

// Resolved values per theme, for tests (contrast checks) and Storybook docs.
const resolvedThemes = Object.fromEntries(
  themes.map((t) => [
    t,
    Object.fromEntries(
      flat.filter(([p]) => p[0] === 'theme' && p[1] === t).map(([p, v]) => [p.slice(2).join('-'), resolveValue(v)]),
    ),
  ]),
);

const ts = `// Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand.
export const tokens = ${JSON.stringify(Object.fromEntries(primitives.map(([p, v]) => [p.join('.'), resolveValue(v)])), null, 2)} as const;

export const themes = ${JSON.stringify(resolvedThemes, null, 2)} as const;

export type ThemeName = keyof typeof themes;
export type SemanticColor = keyof (typeof themes)['dark'];

/** CSS custom property for a semantic colour, e.g. cssVar('action') -> 'var(--dui-color-action)'. */
export const cssVar = (name: SemanticColor) => \`var(--dui-color-\${name})\`;
`;

mkdirSync(resolve(root, 'src/tokens'), { recursive: true });
writeFileSync(resolve(root, 'src/tokens/tokens.css'), css);
writeFileSync(resolve(root, 'src/tokens/tokens.ts'), ts);
console.log(`tokens: ${primitives.length} primitives, ${themes.length} themes (${themes.join(', ')})`);
